-- Run after audit-roles.sql as a PostgreSQL administrator.
BEGIN;

CREATE SCHEMA IF NOT EXISTS audit AUTHORIZATION capstone_audit_owner;
ALTER SCHEMA audit OWNER TO capstone_audit_owner;

CREATE TABLE IF NOT EXISTS public.application_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time TIMESTAMP WITH TIME ZONE NOT NULL,
    level VARCHAR(10) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    actor_username VARCHAR(50),
    subject_username VARCHAR(50),
    exception_type VARCHAR(255),
    http_method VARCHAR(10),
    request_path VARCHAR(500),
    http_status INT,
    duration_ms BIGINT,
    correlation_id VARCHAR(36)
);

ALTER TABLE public.application_logs
    ADD COLUMN IF NOT EXISTS actor_username VARCHAR(50);
ALTER TABLE public.application_logs
    ADD COLUMN IF NOT EXISTS subject_username VARCHAR(50);
ALTER TABLE public.application_logs
    ADD COLUMN IF NOT EXISTS correlation_id VARCHAR(36);

GRANT CREATE ON SCHEMA public TO capstone_audit_owner;
ALTER TABLE public.application_logs OWNER TO capstone_audit_owner;
ALTER SEQUENCE public.application_logs_id_seq OWNER TO capstone_audit_owner;

CREATE INDEX IF NOT EXISTS application_logs_event_time_id_idx
    ON public.application_logs (event_time DESC, id DESC);
REVOKE CREATE ON SCHEMA public FROM capstone_audit_owner;

SET ROLE capstone_audit_owner;

CREATE OR REPLACE FUNCTION audit.prune_application_logs()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, audit, pg_temp
AS $$
BEGIN
    IF NEW.id % 100 = 0 THEN
        DELETE FROM public.application_logs
        WHERE id IN (
            SELECT id FROM public.application_logs
            ORDER BY id DESC
            OFFSET 10000
        );
    END IF;
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION audit.prune_application_logs() FROM PUBLIC;
DROP TRIGGER IF EXISTS prune_application_logs_after_insert ON public.application_logs;
CREATE TRIGGER prune_application_logs_after_insert
    AFTER INSERT ON public.application_logs
    FOR EACH ROW EXECUTE FUNCTION audit.prune_application_logs();

RESET ROLE;

REVOKE ALL ON TABLE public.application_logs FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO capstone_audit_writer, capstone_audit_reader;
GRANT INSERT (event_time, level, event_type, actor_username, subject_username, exception_type,
              http_method, request_path, http_status, duration_ms, correlation_id)
    ON public.application_logs TO capstone_audit_writer;
GRANT USAGE ON SEQUENCE public.application_logs_id_seq TO capstone_audit_writer;
GRANT SELECT (id, event_time, level, event_type, actor_username, subject_username, exception_type,
              http_method, request_path, http_status, duration_ms, correlation_id)
    ON public.application_logs TO capstone_audit_reader;

COMMIT;
